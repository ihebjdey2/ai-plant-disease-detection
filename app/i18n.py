def get_locale() -> str:
    if not has_request_context():
        return "en"
    selected = session.get("language")
    if selected in SUPPORTED_LANGUAGES:
        return selected
    return request.accept_languages.best_match(SUPPORTED_LANGUAGES) or "en"


def translate(message: str, locale: str | None = None) -> str:
    language = locale or get_locale()
    return TRANSLATIONS.get(language, {}).get(message, message)


def translate_disease(label: str, locale: str | None = None) -> str:
    language = locale or get_locale()
    return DISEASE_TRANSLATIONS.get(language, {}).get(label, label)


def translate_status(status: str, locale: str | None = None) -> str:
    keys = {
        "healthy": "Healthy status",
        "diseased": "Diseased status",
        "uncertain": "Uncertain status",
        "no_leaf": "No leaf status",
    }
    return translate(keys.get(status, status.replace("_", " ").title()), locale)


def format_datetime(value: datetime, locale: str | None = None) -> str:
    language = locale or get_locale()
    months = MONTHS.get(language, MONTHS["en"])
    return f"{value.day:02d} {months[value.month - 1]} {value.year}, {value:%H:%M}"
